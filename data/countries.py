# Quick lookup indexes
COUNTRIES_BY_CODE = {c["code"]: c for c in COUNTRIES}

def get_country(code: str):
    """Retrieve country dict by 2-letter ISO code."""
    return COUNTRIES_BY_CODE.get(code.lower())

def search_country_by_name(query: str, lang: str = "en"):
    """Search for country by loose matching name in any language."""
    q = query.strip().lower()
    for c in COUNTRIES:
        for l in ["en", "ru", "uz"]:
            if q == c["name"][l].lower():
                return c
            if q == c["capital"][l].lower():
                return c
    return None
